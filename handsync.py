# ---------------- PREPROCESSING MODULE ----------------
class HandSmoother:
    def __init__(self, alpha=0.25, jitter_threshold=0.8):
        self.alpha = alpha
        self.jitter_threshold = jitter_threshold
        self.prev_smooth = None

    def process(self, current_angles):
        current_angles = np.array(current_angles)

        if self.prev_smooth is None:
            self.prev_smooth = current_angles
            return current_angles.tolist(), True

        smooth_angles = self.alpha * current_angles + (1 - self.alpha) * self.prev_smooth
        jitter = np.abs(smooth_angles - self.prev_smooth)
        has_moved = np.any(jitter > self.jitter_threshold)

        self.prev_smooth = smooth_angles
        return smooth_angles.tolist(), has_moved

hand_preprocessor = HandSmoother(alpha=0.2, jitter_threshold=1.0)

# ---------------- ANGLE CALCULATION (Bhavishya's Fixed Code) ----------------
def calculate_angle(A, B, C):
    A, B, C = np.array(A), np.array(B), np.array(C)
    AB = B - A
    BC = C - B
    denom = (np.linalg.norm(AB) * np.linalg.norm(BC))
    if denom == 0: return 0
    cosine_angle = np.dot(AB, BC) / denom
    cosine_angle = np.clip(cosine_angle, -1.0, 1.0)
    return np.degrees(np.arccos(cosine_angle))

def compute_finger_angles(landmark_list):
    lm = landmark_list
    thumb_angle_1  = calculate_angle(lm[1], lm[2], lm[3])
    thumb_angle_2  = calculate_angle(lm[2], lm[3], lm[4])
    index_angle_1  = calculate_angle(lm[0], lm[5], lm[6])
    index_angle_2  = calculate_angle(lm[5], lm[6], lm[7])
    middle_angle_1 = calculate_angle(lm[0], lm[9], lm[10])
    middle_angle_2 = calculate_angle(lm[9], lm[10], lm[11])
    ring_angle_1   = calculate_angle(lm[0], lm[13], lm[14])
    ring_angle_2   = calculate_angle(lm[13], lm[14], lm[15])
    little_angle_1 = calculate_angle(lm[0], lm[17], lm[18])
    little_angle_2 = calculate_angle(lm[17], lm[18], lm[19])

    # Bhavishya's successful list update!
    return [thumb_angle_1, thumb_angle_2, index_angle_1, index_angle_2, middle_angle_1, middle_angle_2, ring_angle_1, ring_angle_2, little_angle_1, little_angle_2]

# ---------------- SERVO CONTROL ----------------
class ServoManager:
    def __init__(self, port='COM3', baud=115200):
        try:
            self.ser = serial.Serial(port, baud, timeout=0.01)
            print(f"Connected to {port}")
        except:
            self.ser = None
            print("Warning: Serial Port not found. Running in simulation mode.")

        # --- CALIBRATION DATA ---
        # Format: [Biological_Closed_Angle, Biological_Open_Angle]
        # You will need to tweak these numbers based on what you see on your screen!
        self.joint_ranges = [
            [130, 170], [140, 175], # Thumb (Base, Tip)
            [50,  180], [70,  175], # Index (Base, Tip)
            [60,  180], [80,  175], # Middle (Base, Tip)
            [70,  180], [90,  175], # Ring (Base, Tip)
            [80,  180], [100, 170]  # Pinky (Base, Tip)
        ]

    def map_and_send(self, finger_angles):
        if len(finger_angles) < 10:
            return ""

        servo_commands = []
        for i, angle in enumerate(finger_angles):
            # Grab the specific min/max for THIS specific joint
            in_min = self.joint_ranges[i][0]
            in_max = self.joint_ranges[i][1]

            # Map the angle using its specific biological range to the 0-180 servo range
            s_angle = (angle - in_min) * (180 / (in_max - in_min))

            # Safety Constraints: Clamp between 10 and 170 to protect servos
            s_angle = int(max(10, min(170, s_angle)))
            servo_commands.append(s_angle)

        cmd_str = ",".join(map(str, servo_commands))

        if self.ser:
            self.ser.write((cmd_str + "\n").encode())
        return cmd_str

servo = ServoManager()

