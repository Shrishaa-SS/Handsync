def draw_info(image, landmark_list, angles):
    h, w, _ = image.shape
    tip_ids = [4, 8, 12, 16, 20]
    for i, tid in enumerate(tip_ids):
        x = int(landmark_list[tid][0] * w)
        y = int(landmark_list[tid][1] * h)

        # Patch: Safely grab both angles for the current finger
        ang1 = int(angles[i*2])
        ang2 = int(angles[i*2 + 1])
        cv2.putText(image, f"{ang1},{ang2}", (x - 30, y - 20),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 2)

